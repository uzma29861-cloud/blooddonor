// Calculate Haversine distance in kilometers
export function calculateDistanceKm(lat1, lon1, lat2, lon2) {
  if (!lat1 || !lon1 || !lat2 || !lon2) return 0;
  const R = 6371; // Earth radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return parseFloat((R * c).toFixed(2));
}

// Generate realistic polyline points between donor and hospital
export function generateRoutePoints(startLat, startLng, endLat, endLng, steps = 20) {
  const points = [];
  for (let i = 0; i <= steps; i++) {
    const ratio = i / steps;
    const wobble = Math.sin(ratio * Math.PI) * 0.002;
    const lat = startLat + (endLat - startLat) * ratio + wobble;
    const lng = startLng + (endLng - startLng) * ratio + wobble * 0.5;
    points.push([lat, lng]);
  }
  return points;
}

